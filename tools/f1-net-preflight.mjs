// Can this machine receive F1 live timing? A standalone check for any candidate collector host:
// one file, no dependencies, Node 18+ (Node 22+ also tests the live WebSocket).
//   curl -fsSLO https://raw.githubusercontent.com/zKnfz/f1/main/tools/f1-net-preflight.mjs
//   node f1-net-preflight.mjs            human-readable
//   node f1-net-preflight.mjs --json     machine-readable
// It only makes ordinary, honest requests (no browser disguise, no sign-in) and separates:
//   DNS            the name doesn't resolve
//   CONNECT        no TCP/TLS connection (firewall, routing)
//   EDGE_REFUSED   F1's CDN (CloudFront) refuses this network (403 from the CDN itself)
//   APP_REFUSED    F1's server behind the CDN refuses (403 from the application)
//   AUTH           the feed asks for credentials
//   PROTOCOL       negotiate works but the WebSocket/subscribe doesn't
//   NO_SESSION     connected; F1 is between sessions (normal, still a pass)
//   OK             connected and a live snapshot arrived
import dns from 'node:dns/promises';

const HOST = 'livetiming.formula1.com';
const json = process.argv.includes('--json');
const out = { at: new Date().toISOString(), node: process.version, platform: `${process.platform}-${process.arch}`, checks: [], verdict: null };
const add = c => { out.checks.push(c); if (!json) console.log(`${c.ok ? 'ok  ' : 'FAIL'} ${c.name}: ${c.note}`); };
// Response facts that say who answered: the CDN or F1's application.
const facts = (r, body = '') => {
  const h = Object.fromEntries([...r.headers].filter(([k]) => /^(server|content-type|date|x-cache|akamai|x-akamai|x-reference|cf-|x-amz|via|x-served-by)/i.test(k)));
  const ref = /Reference\s*#\s*([\w.]+)/i.exec(body)?.[1] || null;
  const denied = /access denied|forbidden|not authorized|blocked/i.test(body);
  // Who refused: CloudFront itself (its WAF / geo rules answer with its own error page and
  // "server: CloudFront", "x-cache: Error from cloudfront") or F1's application behind it (Kestrel).
  const server = String(h.server || '');
  const by = /cloudfront/i.test(server) || /generated by cloudfront|request could not be satisfied/i.test(body) ? 'cdn' : /kestrel/i.test(server) ? 'app' : server ? 'other' : 'unknown';
  return { status: r.status, headers: h, body: body.replace(/\s+/g, ' ').slice(0, 240), edgeReference: ref, deniedPage: denied, answeredBy: by };
};
async function get(name, url, opts = {}) {
  const t0 = performance.now();
  try {
    const r = await fetch(url, { redirect: 'manual', signal: AbortSignal.timeout(15000), ...opts });
    const body = await r.text().catch(() => '');
    const f = facts(r, body);
    add({ name, ok: r.status < 400, ms: Math.round(performance.now() - t0), ...f, note: `HTTP ${r.status}${f.headers.server ? ` (server: ${f.headers.server})` : ''}${f.edgeReference ? ` ref ${f.edgeReference}` : ''}${f.deniedPage ? ' · denial page' : ''}` });
    return { r, body, f };
  } catch (e) {
    const code = e.cause?.code || e.code || e.name;
    add({ name, ok: false, ms: Math.round(performance.now() - t0), error: code, note: `no response (${code}: ${e.cause?.message || e.message})` });
    return { error: code };
  }
}

// 1. DNS
let addrs = [];
try { addrs = await dns.lookup(HOST, { all: true }); add({ name: 'DNS', ok: true, addresses: addrs.map(a => a.address), note: addrs.map(a => a.address).join(', ') }); }
catch (e) { add({ name: 'DNS', ok: false, note: e.code }); out.verdict = 'DNS'; }

if (!out.verdict) {
  // 2. A control: F1's main site (different service, same company).
  await get('control: www.formula1.com', 'https://www.formula1.com/', { method: 'HEAD' });
  // 3. A static file on the timing host: no protocol at all, so a refusal here is about who is asking.
  const stat = await get('timing host, static file', `https://${HOST}/static/StreamingStatus.json`);
  // 4. The two negotiate endpoints the site uses (SignalR Core, and the legacy one).
  const neg = await get('negotiate (SignalR Core)', `https://${HOST}/signalrcore/negotiate?negotiateVersion=1`, { method: 'POST' });
  // (Information only: the legacy endpoint answers 401 even where everything works; Pitwall doesn't use it.)
  const legacy = await get('negotiate (legacy SignalR, info only)', `https://${HOST}/signalr/negotiate?connectionData=${encodeURIComponent('[{"name":"Streaming"}]')}&clientProtocol=1.5`);
  if (legacy.r) out.checks.at(-1).ok = true;
  // 5. Same request, with a plain honest client name instead of Node's default.
  await get('negotiate, named client', `https://${HOST}/signalrcore/negotiate?negotiateVersion=1`, { method: 'POST', headers: { 'User-Agent': 'pitwall-collector-preflight' } });

  const skew = neg.r?.headers.get('date') ? Date.parse(neg.r.headers.get('date')) - Date.now() : null;
  if (skew != null) out.clockSkewS = +(skew / 1000).toFixed(1);

  if (neg.error || stat.error) out.verdict = 'CONNECT';
  else if (neg.r.status === 401) out.verdict = 'AUTH';
  else if (neg.r.status === 403 && neg.f.answeredBy === 'cdn') out.verdict = stat.r.status === 403 ? 'EDGE_REFUSED' : 'EDGE_REFUSED_DYNAMIC';
  else if (neg.r.status === 403) out.verdict = 'APP_REFUSED';
  else if (neg.r.status >= 400) out.verdict = `HTTP_${neg.r.status}`;
  else if (typeof WebSocket === 'undefined') out.verdict = 'NEGOTIATE_OK_NO_WS_TEST';
  else {
    // 6. The live connection: subscribe and wait for the snapshot.
    const t0 = performance.now();
    try {
      const cookie = (neg.r.headers.getSetCookie?.() || []).map(x => x.split(';')[0]).join('; ');
      const { connectionToken } = JSON.parse(neg.body);
      const ws = new WebSocket(`wss://${HOST}/signalrcore?id=${encodeURIComponent(connectionToken)}`, { headers: { Cookie: cookie } });
      const snap = await new Promise((res, rej) => {
        const t = setTimeout(() => rej(new Error('no snapshot in 15 s')), 15000);
        ws.onerror = e => { clearTimeout(t); rej(new Error('WebSocket error ' + (e.message || ''))); };
        ws.onopen = () => { ws.send('{"protocol":"json","version":1}\x1e'); ws.send(JSON.stringify({ type: 1, target: 'Subscribe', arguments: [['SessionInfo', 'SessionStatus', 'Heartbeat']], invocationId: '0' }) + '\x1e'); };
        ws.onmessage = e => { for (const p of String(e.data).split('\x1e')) { try { const m = JSON.parse(p); if (m.type === 3) { clearTimeout(t); res(m.result || {}); } } catch {} } };
      });
      ws.close();
      const st = snap.SessionStatus?.Status;
      add({ name: 'live connection', ok: true, ms: Math.round(performance.now() - t0), note: `snapshot: ${snap.SessionInfo?.Meeting?.Name} ${snap.SessionInfo?.Name} (${st})` });
      out.verdict = /Started|Inactive|Aborted/.test(st || '') ? 'OK' : 'NO_SESSION';
    } catch (e) { add({ name: 'live connection', ok: false, ms: Math.round(performance.now() - t0), note: e.message }); out.verdict = 'PROTOCOL'; }
  }
}
const meaning = {
  OK: 'this machine can collect F1 live timing',
  NO_SESSION: 'this machine can collect F1 live timing (F1 is between sessions now)',
  NEGOTIATE_OK_NO_WS_TEST: 'negotiate works; use Node 22+ to test the live connection too',
  EDGE_REFUSED: "F1's CDN (CloudFront) refuses this network for everything on the timing host, before any protocol step. Not fixable by credentials or code; use a different network",
  EDGE_REFUSED_DYNAMIC: "F1's CDN (CloudFront) serves static files to this network but refuses the live-timing endpoint: a rule on who may connect, applied before F1's server sees the request. Not fixable by credentials or code; use a different network",
  APP_REFUSED: "F1's own server (behind the CDN) refuses negotiate for this request. Compare with a machine where it works: same tool, same request, so a difference points to the network",
  AUTH: 'the feed asks for credentials (unexpected: it is public)',
  PROTOCOL: 'negotiate works but the live connection does not (could be a proxy/firewall blocking WebSockets)',
  CONNECT: 'no connection to the timing host (firewall/routing)',
  DNS: 'the timing host name does not resolve',
};
out.meaning = meaning[out.verdict] || 'unexpected HTTP status; see the checks';
if (json) console.log(JSON.stringify(out, null, 1));
else console.log(`\nVERDICT ${out.verdict}: ${out.meaning}${out.clockSkewS != null ? ` · clock vs F1 ${out.clockSkewS >= 0 ? '+' : ''}${out.clockSkewS} s` : ''}`);
process.exit(['OK', 'NO_SESSION', 'NEGOTIATE_OK_NO_WS_TEST'].includes(out.verdict) ? 0 : 1);
